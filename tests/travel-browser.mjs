import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { defaults, stateURL } from '../src/state.js';
import { travelURL } from '../src/travel-time.js';
import { clockCatalog } from '../src/catalog.js';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true});
const context = await browser.newContext({viewport:{width:1440,height:1100},timezoneId:'Asia/Singapore',colorScheme:'dark'});
const page = await context.newPage();
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await mkdir('test-results',{recursive:true});
const base=process.env.TEST_URL || 'http://127.0.0.1:4173/';
const waitReady=()=>page.waitForFunction(()=>document.querySelector('#clocks').getAttribute('aria-busy')==='false' && document.querySelector('.clock-card'));
try {
  await page.goto(base); await waitReady();
  await page.locator('#time-travel').click();
  assert.equal(await page.locator('#travel-zone').inputValue(),'Asia/Singapore');
  await page.locator('#freeze-now').click();
  assert.equal(await page.locator('#frozen-banner').isVisible(),true);
  const frozen = await page.locator('.time-display').allTextContents();
  await page.waitForTimeout(1200);
  assert.deepEqual(await page.locator('.time-display').allTextContents(),frozen);
  await page.locator('#adjust-time').click();
  await page.locator('#travel-zone').selectOption('America/Los_Angeles');
  await page.locator('#travel-datetime').fill('2026-03-08T02:30');
  assert.equal(await page.locator('#travel-error').isVisible(),true);
  assert.equal(await page.locator('#travel-apply').isDisabled(),true);
  await page.locator('#travel-datetime').fill('2026-11-01T01:30');
  assert.equal(await page.locator('#travel-fold').isVisible(),true);
  await page.locator('#travel-occurrence').selectOption('1');
  await page.locator('#travel-apply').click();
  assert.equal(new URL(page.url()).searchParams.get('at'),'2026-11-01T09:30:00Z');
  assert.equal(await page.locator('[data-id="geonames:5368361"] .zone-code').textContent(),'PST');
  assert.equal(await page.locator('[data-id="utc"] .time-main').textContent(),'09:30');
  assert.equal(await page.locator('[data-id="geonames:1275004"] .time-main').textContent(),'15:00');
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:async text=>window.copied=text},configurable:true}));
  await page.locator('#copy-times').click();
  assert.match(await page.evaluate(()=>window.copied),/UTC — 09:30:00 UTC/);
  await page.locator('#copy-link').click();
  assert.equal(await page.evaluate(()=>window.copied),page.url());
  await page.locator('[data-id="utc"] .flip-open').click();
  await page.locator('[data-id="utc"] [data-mode="digital"]').click();
  await page.locator('[data-id="utc"] .flip-close').click();
  assert.equal(new URL(page.url()).searchParams.get('at'),'2026-11-01T09:30:00Z');
  const saved=page.url();
  await page.reload(); await waitReady();
  assert.equal(await page.locator('#frozen-banner').isVisible(),true);
  await page.locator('#resume-time').click();
  assert.equal(new URL(page.url()).searchParams.has('at'),false);
  assert.equal(await page.locator('#frozen-banner').isHidden(),true);
  const second=await page.locator('.time-seconds').first().textContent();
  await page.waitForFunction(s=>document.querySelector('.time-seconds').textContent!==s,second);
  await page.goBack(); await page.waitForSelector('body.time-frozen');
  assert.equal(page.url(),saved);
  await page.locator('#adjust-time').click();
  await page.locator('[data-time-shift="1"]').click();
  await page.locator('#travel-apply').click();
  assert.equal(new URL(page.url()).searchParams.get('at'),'2026-11-01T10:30:00Z');
  await page.screenshot({path:'test-results/time-travel-frozen.png'});
  await page.locator('#adjust-time').click();
  await page.screenshot({path:'test-results/time-travel-picker.png'});
  await page.locator('#cancel-travel').click();
  assert.equal(new URL(page.url()).searchParams.get('at'),'2026-11-01T10:30:00Z');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#adjust-time').click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'test-results/time-travel-mobile.png'});
  await page.locator('#cancel-travel').click();
  const catalog=clockCatalog(JSON.parse(await readFile(new URL('../data/clock-catalog-2026-10-14.json',import.meta.url))));
  const many=[...catalog.values()].slice(0,1000).map(c=>({...c,display:'analog',hours:24}));
  await page.goto(travelURL(stateURL(base,many),new Date('2026-11-01T09:30:00Z'))); await waitReady();
  await page.locator('.clock-slot').last().scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>document.querySelector('.clock-slot:last-child .clock-card'));
  assert.ok(await page.locator('.clock-card').count()<12);
  const offscreen=await page.locator('.clock-slot:last-child .time-display').textContent();
  await page.waitForTimeout(1200);
  assert.equal(await page.locator('.clock-slot:last-child .time-display').textContent(),offscreen);
  await page.goto(`${base}?at=invalid`); await waitReady();
  assert.equal(await page.locator('#notice').isVisible(),true);
  await page.locator('#restore').click();
  assert.equal(new URL(page.url()).searchParams.has('at'),false);
  assert.deepEqual(errors,[]);
  console.log('PASS Time Travel: freeze/live, zone picker, DST gap/fold, all zones, copy, reload, history, time shifts, mobile, and virtualized 1,000 clocks.');
} finally {await browser.close();}
