import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { clockCatalog } from '../src/catalog.js';
import { defaults, stateURL, readState } from '../src/state.js';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1200, height: 900 }, colorScheme: 'dark' });
const base = process.env.TEST_URL || 'http://127.0.0.1:4173/';
const catalog = clockCatalog(JSON.parse(await readFile(new URL('../data/clock-catalog-2026-10-14.json', import.meta.url))));
const errors = []; page.on('pageerror', e => errors.push(e.message));
await mkdir('test-results', { recursive: true });
try {
  await page.goto(stateURL(base, defaults()));
  const card = page.locator('.clock-card').first();
  await card.locator('.design-open').click();
  assert.equal(await card.locator('.design-settings').isVisible(), true);
  assert.equal(await card.locator('.clock-settings').isVisible(), false);
  assert.equal(await card.locator('[data-palette-choice="1"] > span:last-child').isVisible(), false);
  assert.equal(await card.locator('[data-palette-choice="1"]').getAttribute('aria-label'), 'Ocean');
  await card.locator('[data-palette-choice="1"]').click();
  await card.locator('button[data-finish="8"]').click();
  await card.locator('button[data-dial="16"]').click();
  assert.equal(readState(page.url(), catalog).clocks[0].design, 25);
  await card.locator('.flip-close').click();
  assert.equal(await card.locator('.design-open').evaluate(el => el === document.activeElement), true);
  assert.equal(await card.locator('.numerals').evaluate(el => getComputedStyle(el).visibility), 'hidden');
  const dark = await card.locator('.card-front').evaluate(el => getComputedStyle(el).backgroundImage);
  await page.locator('[data-theme-choice="light"]').click();
  const light = await card.locator('.card-front').evaluate(el => getComputedStyle(el).backgroundImage);
  assert.notEqual(dark, light);
  await page.reload(); await page.waitForSelector('.clock-card');
  assert.equal(await card.locator('.card-front').getAttribute('data-palette'), '1');
  await card.locator('.flip-open').click();
  assert.equal(await card.locator('.clock-settings').isVisible(), true);
  await card.locator('[data-mode="digital"]').click();
  assert.equal(readState(page.url(), catalog).clocks[0].design, 25);
  await card.locator('.flip-close').click();
  await card.locator('.design-open').click();
  await card.locator('.design-reset').click();
  assert.equal(readState(page.url(), catalog).clocks[0].design, undefined);
  await page.goBack();
  await page.waitForFunction(() => document.querySelector('.card-front').dataset.palette === '1');
  await card.locator('.flip-close').click();
  await page.locator('[data-card-view="standard"]').click();
  await card.locator('.design-open').click();
  assert.equal(await card.locator('[data-palette-choice="1"] > span:last-child').isVisible(), true);
  const palettes = [...catalog.values()].slice(0, 6).map((c, i) => ({ ...c, display: 'analog', hours: 24, design: i + 8 }));
  await page.goto(stateURL(base, palettes)); await page.waitForSelector('.clock-card');
  await page.screenshot({ path: 'test-results/card-designs-light.png' });
  await page.locator('[data-theme-choice="dark"]').click();
  await page.screenshot({ path: 'test-results/card-designs-dark.png' });
  await page.setViewportSize({ width: 320, height: 800 });
  await card.locator('.design-open').click();
  await card.locator('[data-palette-choice="5"]').click();
  await card.locator('button[data-finish="8"]').click();
  await card.locator('button[data-dial="16"]').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await card.locator('.flip-close').click();
  await card.locator('.design-open').click();
  await card.locator('.flip-close').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/card-designs-mobile.png' });
  assert.deepEqual(errors, []);
  console.log('PASS card designs: separate panels, URL persistence, reset/history, light/dark, formats, keyboard focus, 320px controls.');
} finally { await browser.close(); }
